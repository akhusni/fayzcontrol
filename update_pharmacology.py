def main():
    base_dir = os.path.dirname(os.path.abspath(__file__))
    data_dir = os.path.join(base_dir, "data")
    db_path = os.path.join(data_dir, "pharmacology_db.json")
    fayz_path = os.path.join(data_dir, "fayz_house_meds.json")

    # 1. Build records for all 88 medications
    fayz_records = [build_medication_record(m) for m in CLINIC_MEDS]
    print(f"Built {len(fayz_records)} clinic medication records.")

    # Save standalone fayz_house_meds.json for quick client-side access
    with open(fayz_path, "w", encoding="utf-8") as f:
        json.dump({
            "title": "Fayz Medical House Official Formulary (88 Medications)",
            "count": len(fayz_records),
            "medications": fayz_records
        }, f, ensure_ascii=False, indent=2)
    print(f"Saved {fayz_path}")

    # 2. Update master pharmacology_db.json
    with open(db_path, "r", encoding="utf-8") as f:
        db = json.load(f)

    existing_meds = db.get("medications", [])
    
    # Normalize existing meds to guarantee .name and .form properties
    for m in existing_meds:
        if not m.get("name"):
            m["name"] = m.get("trade_name_uz") or m.get("trade_name", "").split("/")[0].strip()
        if not m.get("form"):
            df = m.get("dosage_form", "")
            if "flakon" in df.lower() or "infus" in df.lower():
                m["form"] = "Infuzion flakon"
            elif "ampul" in df.lower() or "inyeksiya" in df.lower() or "amp" in df.lower():
                m["form"] = "Ampula"
            elif "tab" in df.lower():
                m["form"] = "Tabletkalar"
            elif "caps" in df.lower() or "kaps" in df.lower():
                m["form"] = "Kapsulalar"
            else:
                m["form"] = "Tabletkalar"

    # Merge: keep existing meds and prepend/update fayz_records
    med_dict = {m["id"]: m for m in existing_meds}
    for fr in fayz_records:
        med_dict[fr["id"]] = fr

    all_meds = list(med_dict.values())
    db["medications"] = all_meds
    db["metadata"]["total_medications"] = len(all_meds)
    db["metadata"]["clinic_formulary_count"] = len(fayz_records)
    db["metadata"]["last_updated"] = "2026-09-08"

    with open(db_path, "w", encoding="utf-8") as f:
        json.dump(db, f, ensure_ascii=False, indent=2)
    print(f"Updated {db_path}: now has {len(all_meds)} medications ({len(fayz_records)} clinic formulary).")

if __name__ == "__main__":
    main()
